export type CollectionKey = (typeof COLLECTION_KEYS)[number];

export interface CollectionDef {
  key: CollectionKey;
  label: string;
  singular: string;
  description: string;
  /** Field shown as the row title in admin lists. */
  titleField: string;
  /** Extra column(s) shown under the title in admin lists. */
  subtitleFields?: string[];
  /** Draft/published/archived workflow (taxonomies are always live). */
  publishable: boolean;
  /** Admin list order: manual sort order, or newest first by a date column. */
  order: { kind: "manual" } | { kind: "date"; field: string } | { kind: "alpha"; field: string };
  fields: FieldDef[];
  /** Fields that must be filled before the item can be published. */
  requiredToPublish?: string[];
  /** Public page for an item, used for "View" and preview links. */
  publicPath?: (row: Record<string, unknown>) => string | null;
}

